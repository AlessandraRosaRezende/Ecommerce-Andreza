import mongoose from "mongoose";
import { IProduct } from "../interfaces/IProduct.js";

const productSchema = new mongoose.Schema({
  name: {
    type: String,
    required: true,
  },
  description: {
    type: String,
    required: true,
  },
  price: {
    type: Number,
    required: true,
    min: 0,
  },
  stock: {
    type: Number,
    required: true,
    min: 0,
    default: 0,
  },
  category: {
    type: String,
    required: true,
  },
}, { timestamps: true });

export const Product = mongoose.model<IProduct>("Product", productSchema);